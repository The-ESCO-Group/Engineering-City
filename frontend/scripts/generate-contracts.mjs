import { readFile, writeFile, mkdir } from "node:fs/promises";
import { fileURLToPath, pathToFileURL } from "node:url";
import { dirname, join, resolve } from "node:path";

import openapiTS, { astToString } from "openapi-typescript";

const EXPECTED_CONTRACT_VERSION = "1.1.0";
const CHECK_MODE = process.argv.slice(2).includes("--check");
const unsupportedArgs = process.argv.slice(2).filter((arg) => arg !== "--check");

if (unsupportedArgs.length > 0) {
  throw new Error(`Unsupported argument(s): ${unsupportedArgs.join(", ")}`);
}

const scriptDirectory = dirname(fileURLToPath(import.meta.url));
const frontendRoot = resolve(scriptDirectory, "..");
const repositoryRoot = resolve(frontendRoot, "..");
const contractRoot = join(repositoryRoot, "contracts");
const generatedRoot = join(frontendRoot, "src", "generated");
const openapiPath = join(contractRoot, "openapi.yaml");
const eventsPath = join(contractRoot, "events.schema.json");

const normalize = (value) => `${value.replaceAll("\r\n", "\n").trimEnd()}\n`;

function readOpenApiContractVersion(source) {
  const infoBlock = source.match(/^info:\s*$([\s\S]*?)(?=^[^\s#])/m)?.[1];
  const version = infoBlock?.match(/^\s+x-contract-version:\s*["']?([^\s#"']+)/m)?.[1];

  if (!version) {
    throw new Error("contracts/openapi.yaml is missing info.x-contract-version");
  }

  return version;
}

function assertContractVersion(sourceName, actualVersion) {
  if (actualVersion !== EXPECTED_CONTRACT_VERSION) {
    throw new Error(
      `${sourceName} declares contract version ${actualVersion}; ` +
        `the frontend is pinned to ${EXPECTED_CONTRACT_VERSION}. ` +
        "Review the contract change before updating the generator pin.",
    );
  }
}

function prepareEventDefinitions(definitions) {
  const prepared = structuredClone(definitions);
  const visit = (value) => {
    if (Array.isArray(value)) {
      value.forEach(visit);
      return;
    }
    if (!value || typeof value !== "object") {
      return;
    }
    if (typeof value.$ref === "string") {
      value.$ref = value.$ref.replace("#/$defs/", "#/components/schemas/");
    }
    Object.values(value).forEach(visit);
  };
  visit(prepared);
  return prepared;
}

async function buildOutputs() {
  const [openapiSource, eventsSource] = await Promise.all([
    readFile(openapiPath, "utf8"),
    readFile(eventsPath, "utf8"),
  ]);
  const eventsSchema = JSON.parse(eventsSource);
  const openapiContractVersion = readOpenApiContractVersion(openapiSource);
  const eventsContractVersion = eventsSchema["x-contract-version"];

  assertContractVersion("contracts/openapi.yaml", openapiContractVersion);
  assertContractVersion("contracts/events.schema.json", eventsContractVersion);

  const openapiAst = await openapiTS(pathToFileURL(openapiPath), {
    alphabetize: true,
    defaultNonNullable: false,
    exportType: true,
    immutable: true,
    silent: true,
  });
  const openapiTypes = astToString(openapiAst);
  const eventDefinitionNames = Object.keys(eventsSchema.$defs ?? {}).sort();
  if (!eventDefinitionNames.includes("EventEnvelope")) {
    throw new Error("contracts/events.schema.json is missing $defs.EventEnvelope");
  }
  if (eventDefinitionNames.some((name) => !/^[A-Za-z_$][\w$]*$/.test(name))) {
    throw new Error("contracts/events.schema.json contains a definition name that is not a TypeScript identifier");
  }
  const eventAst = await openapiTS(
    {
      openapi: "3.1.0",
      info: {
        title: eventsSchema.title,
        version: eventsContractVersion,
      },
      components: {
        schemas: prepareEventDefinitions(eventsSchema.$defs),
      },
    },
    {
      alphabetize: true,
      defaultNonNullable: false,
      exportType: true,
      immutable: true,
      silent: true,
    },
  );
  const eventAliases = [
    "export type EventComponents = components;",
    ...eventDefinitionNames.map(
      (name) => `export type ${name} = components["schemas"]["${name}"];`,
    ),
  ].join("\n");
  const eventTypes = astToString(eventAst);

  const generatedOpenapi = normalize(
    [
      "/**",
      " * Generated from contracts/openapi.yaml by openapi-typescript.",
      " * Do not edit this file directly; run `npm run contracts:generate`.",
      " */",
      openapiTypes,
    ].join("\n"),
  );
  const generatedEvents = normalize(
    [
      "/**",
      " * Generated from contracts/events.schema.json by openapi-typescript.",
      " * Do not edit this file directly; run `npm run contracts:generate`.",
      " */",
      eventTypes,
      eventAliases,
    ].join("\n"),
  );
  const generatedVersion = normalize(`/** Generated contract compatibility metadata. */
export const CONTRACT_VERSION = "${EXPECTED_CONTRACT_VERSION}" as const;
export const OPENAPI_CONTRACT_VERSION = "${openapiContractVersion}" as const;
export const EVENTS_CONTRACT_VERSION = "${eventsContractVersion}" as const;
`);
  const generatedIndex = normalize(`/** Generated contract surface. */
export type { paths, webhooks, components, $defs, operations } from "./openapi";
export type {
${eventDefinitionNames.map((name) => `  ${name},`).join("\n")}
  EventComponents,
} from "./events";
export * from "./contract-version";
`);

  return new Map([
    ["openapi.ts", generatedOpenapi],
    ["events.ts", generatedEvents],
    ["contract-version.ts", generatedVersion],
    ["index.ts", generatedIndex],
  ]);
}

async function checkOutputs(outputs) {
  const drifted = [];

  for (const [filename, expected] of outputs) {
    try {
      const actual = normalize(await readFile(join(generatedRoot, filename), "utf8"));
      if (actual !== expected) {
        drifted.push(filename);
      }
    } catch (error) {
      if (error?.code === "ENOENT") {
        drifted.push(filename);
        continue;
      }
      throw error;
    }
  }

  if (drifted.length > 0) {
    throw new Error(
      `Generated contract files are stale: ${drifted.join(", ")}. ` +
        "Run `npm run contracts:generate` and commit the result.",
    );
  }

  console.log(`Generated contracts are current (contract ${EXPECTED_CONTRACT_VERSION}).`);
}

async function writeOutputs(outputs) {
  await mkdir(generatedRoot, { recursive: true });
  await Promise.all(
    [...outputs].map(([filename, contents]) =>
      writeFile(join(generatedRoot, filename), contents, "utf8"),
    ),
  );
  console.log(`Generated ${outputs.size} contract files for contract ${EXPECTED_CONTRACT_VERSION}.`);
}

const outputs = await buildOutputs();
if (CHECK_MODE) {
  await checkOutputs(outputs);
} else {
  await writeOutputs(outputs);
}
