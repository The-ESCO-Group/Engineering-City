"""record the revision an approval covers

Revision ID: 4000cd6b1757
Revises: 4f7a9c2d1e6b
Created: 2026-08-05 12:26:30.331309

Every canonical engineering object already recorded who approved it and when.
Neither answers the question the approval exists to answer — *what* was signed —
so "approved, and edited since" had to be inferred from ``updated_at`` against
``approved_at``. Recording an approval is itself an update, so those two are two
reads of the same wall clock inside one flush; their order is undefined, and an
approval could read as a later edit of the very object it approved.
``approved_object_revision`` makes the comparison exact:
``object_revision`` moves only on an update, so an object edited since its
approval is one whose revision has passed the approved one.

Existing approvals are left null rather than backfilled from ``object_revision``.
The revision they covered was never recorded, and setting it to whatever the row
holds now would assert that nothing has changed since — which is precisely the
claim this column exists to establish rather than assume. Null is read as "not
recorded, so not checkable" and reported as such; the next approval of an object
records a real baseline.
"""

